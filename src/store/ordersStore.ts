import { create } from 'zustand';
import * as Crypto from 'expo-crypto';
import type {
  Address,
  CartLine,
  DeliveryStatus,
  OrderRecord,
  Restaurant,
} from '../types';
import { loadOrders, saveOrders } from '../lib/storage';
import { restaurantById } from '../data/restaurants';
import { isSupabaseConfigured, supabase } from '../lib/supabase';

const cents = (dollars: number) => Math.round(dollars * 100);

/** How far back to ask the server for delivery progress. Orders older than this
 *  have long since finished; their last known status is already on the record. */
const SYNC_WINDOW_MS = 7 * 24 * 60 * 60 * 1000;

interface OrdersState {
  ownerEmail: string | null;
  orders: OrderRecord[];
  /** Distinct restaurants the user has ordered from, most-recent first. */
  recentRestaurants: Restaurant[];

  configure: (email: string | null) => Promise<void>;
  record: (input: {
    /** The dispatch order id, generated by placeOrder before payment. Passed in
     *  rather than minted here so the local record and the server row share one
     *  identity — see OrderRecord.id. */
    id: string;
    orderNumber: string | null;
    lines: CartLine[];
    subtotal: number;
    deliveryFee: number;
    tip: number;
    total: number;
    restaurantID: string;
    restaurantName: string;
    deliveryAddress: Address | null;
    paymentIntentID: string;
  }) => Promise<OrderRecord>;
  /** Refresh delivery progress for recent orders from the shared orders table. */
  syncDeliveryStatus: () => Promise<void>;
  /** Merge server-owned fields into one local record. The single write path for
   *  everything the backend knows and the device doesn't — used by the status
   *  sync, the realtime tracking feed, and dispatch handing back the order
   *  number. Undefined fields are left alone; a no-op change doesn't re-render. */
  updateFromServer: (orderId: string, patch: ServerOrderPatch) => void;
  byId: (id: string) => OrderRecord | undefined;
}

export interface ServerOrderPatch {
  orderNumber?: string | null;
  deliveryStatus?: DeliveryStatus | null;
  pickupPhotoURL?: string | null;
}

function deriveRecent(orders: OrderRecord[]): Restaurant[] {
  const seen = new Set<string>();
  const result: Restaurant[] = [];
  for (const order of orders) {
    if (seen.has(order.restaurantID)) continue;
    seen.add(order.restaurantID);
    const restaurant = restaurantById(order.restaurantID);
    if (restaurant) result.push(restaurant);
  }
  return result;
}

/**
 * Older records were written before orders carried a number, a delivery status,
 * or a pickup photo. They're already in AsyncStorage on real devices, so read
 * them forward rather than dropping someone's history on upgrade.
 */
function migrate(order: OrderRecord): OrderRecord {
  return {
    ...order,
    orderNumber: order.orderNumber ?? null,
    deliveryStatus: order.deliveryStatus ?? null,
    pickupPhotoURL: order.pickupPhotoURL ?? null,
  };
}

export const useOrdersStore = create<OrdersState>((set, get) => ({
  ownerEmail: null,
  orders: [],
  recentRestaurants: [],

  configure: async (email) => {
    if (!email) {
      set({ ownerEmail: null, orders: [], recentRestaurants: [] });
      return;
    }
    const orders = (await loadOrders(email))
      .map(migrate)
      .sort((a, b) => new Date(b.placedAt).getTime() - new Date(a.placedAt).getTime());
    set({ ownerEmail: email, orders, recentRestaurants: deriveRecent(orders) });
    // Catch up on anything the drivers did while this account was signed out.
    void get().syncDeliveryStatus();
  },

  record: async ({
    id,
    orderNumber,
    lines,
    subtotal,
    deliveryFee,
    tip,
    total,
    restaurantID,
    restaurantName,
    deliveryAddress,
    paymentIntentID,
  }) => {
    const order: OrderRecord = {
      id,
      // `record` is only reachable from a signed-in checkout, but the store's
      // owner is set asynchronously on auth change; falling back to the address
      // owner keeps the record self-consistent if they ever disagree.
      ownerEmail: get().ownerEmail ?? deliveryAddress?.ownerEmail ?? '',
      restaurantID,
      restaurantName,
      placedAt: new Date().toISOString(),
      status: 'Placed',
      orderNumber,
      deliveryStatus: null,
      pickupPhotoURL: null,
      currency: 'cad',
      subtotalCents: cents(subtotal),
      deliveryFeeCents: cents(deliveryFee),
      tipCents: cents(tip),
      totalCents: cents(total),
      paymentIntentID,
      items: lines.map((line) => ({
        id: Crypto.randomUUID(),
        menuItemID: line.item.id,
        name: line.item.name,
        unitPriceCents: cents(line.item.price),
        quantity: line.quantity,
        lineTotalCents: cents(line.item.price) * line.quantity,
      })),
      deliveryAddressLine: deliveryAddress?.addressLine ?? '',
      deliveryApartmentSuite: deliveryAddress?.apartmentSuite ?? '',
      deliveryInstructions: deliveryAddress?.instructions ?? '',
      deliveryPreference: deliveryAddress?.deliveryPreference ?? '',
    };

    const email = get().ownerEmail;
    const orders = [order, ...get().orders];
    // Returned even when there's no owner to persist under, so the confirmation
    // screen can always show what was just ordered.
    if (email) await saveOrders(email, orders);
    set({ orders, recentRestaurants: deriveRecent(orders) });
    return order;
  },

  syncDeliveryStatus: async () => {
    const email = get().ownerEmail;
    if (!email || !isSupabaseConfigured || !supabase) return;

    const recent = get().orders.filter(
      (o) => Date.now() - new Date(o.placedAt).getTime() < SYNC_WINDOW_MS,
    );
    if (recent.length === 0) return;

    // Local ids ARE the server ids (see OrderRecord.id), so this is a direct
    // lookup — no join table, no matching on payment intent.
    const { data, error } = await supabase
      .from('orders')
      .select('id, order_number, delivery_status, pickup_photo_url')
      .in(
        'id',
        recent.map((o) => o.id),
      );
    if (error || !data) return;

    const live = new Map(data.map((row) => [row.id as string, row]));
    let changed = false;
    const orders = get().orders.map((order) => {
      const row = live.get(order.id);
      if (!row) return order;
      const next = merge(order, {
        orderNumber: row.order_number as string | null,
        deliveryStatus: row.delivery_status as DeliveryStatus | null,
        pickupPhotoURL: row.pickup_photo_url as string | null,
      });
      if (next !== order) changed = true;
      return next;
    });

    if (!changed) return;
    await saveOrders(email, orders);
    set({ orders });
  },

  updateFromServer: (orderId, patch) => {
    let changed = false;
    const orders = get().orders.map((order) => {
      if (order.id !== orderId) return order;
      const next = merge(order, patch);
      if (next !== order) changed = true;
      return next;
    });
    if (!changed) return;
    set({ orders });
    // Fire-and-forget: the in-memory copy is what the UI reads, and losing one
    // write to disk only costs a re-sync on next launch.
    const email = get().ownerEmail;
    if (email) void saveOrders(email, orders);
  },

  byId: (id) => get().orders.find((order) => order.id === id),
}));

/**
 * Apply a server patch, returning the SAME object when nothing actually
 * changed so callers can detect a no-op by identity (and skip a disk write and
 * a re-render).
 *
 * A null in the patch means "the server has no value for this yet" — an order
 * no driver has claimed has a null delivery_status — so nulls never clear a
 * field the device already knows.
 */
function merge(order: OrderRecord, patch: ServerOrderPatch): OrderRecord {
  const next: OrderRecord = {
    ...order,
    orderNumber: patch.orderNumber ?? order.orderNumber,
    deliveryStatus: patch.deliveryStatus ?? order.deliveryStatus,
    pickupPhotoURL: patch.pickupPhotoURL ?? order.pickupPhotoURL,
  };
  const same =
    next.orderNumber === order.orderNumber &&
    next.deliveryStatus === order.deliveryStatus &&
    next.pickupPhotoURL === order.pickupPhotoURL;
  return same ? order : next;
}
